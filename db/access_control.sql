-- db/access_control.sql — Access Control (modules + role permissions)
CREATE TABLE IF NOT EXISTS modules (
  id     BIGSERIAL PRIMARY KEY,
  name   TEXT NOT NULL,
  key    TEXT UNIQUE NOT NULL,
  grp    TEXT NOT NULL,
  type   TEXT NOT NULL,              -- Page | Button | Data Point
  active BOOLEAN NOT NULL DEFAULT true,
  sort   INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS role_permissions (
  role_key   TEXT NOT NULL REFERENCES roles(key) ON DELETE CASCADE,
  module_key TEXT NOT NULL REFERENCES modules(key) ON DELETE CASCADE,
  perm_key   TEXT NOT NULL,          -- view|add|edit|delete|approve|export|reports|dash
  PRIMARY KEY (role_key, module_key, perm_key)
);
CREATE INDEX IF NOT EXISTS idx_role_perms_role ON role_permissions (role_key);

